<script>
  document.addEventListener('DOMContentLoaded', function () {
    // Toggle New Password
    const toggleNew = document.getElementById('toggleNewPassword');
    const newPwd = document.getElementById('password');
    if (toggleNew && newPwd) {
      toggleNew.addEventListener('click', function () {
        const icon = this.querySelector('i');
        newPwd.type = newPwd.type === 'password' ? 'text' : 'password';
        icon.classList.toggle('ri-eye-off-line');
        icon.classList.toggle('ri-eye-line');
      });
    }
    // Toggle Confirm Password
    const toggleConfirm = document.getElementById('toggleConfirmPassword');
    const confirmPwd = document.getElementById('password_confirmation');
    if (toggleConfirm && confirmPwd) {
      toggleConfirm.addEventListener('click', function () {
        const icon = this.querySelector('i');
        confirmPwd.type = confirmPwd.type === 'password' ? 'text' : 'password';
        icon.classList.toggle('ri-eye-off-line');
        icon.classList.toggle('ri-eye-line');
      });
    }
  });
</script>
