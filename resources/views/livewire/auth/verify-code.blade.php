<script>
  document.addEventListener('DOMContentLoaded', function () {
    const otpWrapper = document.getElementById('otpWrapperVerify');
    const submitBtn = document.getElementById('verifySubmitBtn');
    const inputs = otpWrapper ? Array.from(otpWrapper.querySelectorAll('.otp-digit-input')) : [];

    function syncLivewire() {
      const value = inputs.map(i => i.value).join('');
      // Sync to Livewire model via dispatch
      if (window.Livewire) {
        const wireId = document.querySelector('[wire\\:id]')?.getAttribute('wire:id');
        if (wireId) {
          const component = Livewire.find(wireId);
          if (component) component.set('codeInputs', inputs.reduce((acc, inp, idx) => { acc[idx] = inp.value; return acc; }, {}));
        }
      }
      // Visual feedback
      inputs.forEach(inp => inp.classList.toggle('otp-filled', inp.value.length > 0));
      return value;
    }

    inputs.forEach((input, idx) => {
      input.addEventListener('keydown', function (e) {
        if (e.key === 'Backspace') {
          if (this.value === '' && idx > 0) {
            inputs[idx - 1].value = '';
            inputs[idx - 1].focus();
          } else {
            this.value = '';
          }
          syncLivewire();
          e.preventDefault();
        } else if (e.key === 'ArrowLeft' && idx > 0) {
          inputs[idx - 1].focus(); e.preventDefault();
        } else if (e.key === 'ArrowRight' && idx < inputs.length - 1) {
          inputs[idx + 1].focus(); e.preventDefault();
        } else if (e.key === 'Enter') {
          e.preventDefault();
          const val = syncLivewire();
          if (val.length === 6) submitBtn.click();
        }
      });

      input.addEventListener('input', function () {
        this.value = this.value.replace(/[^0-9]/g, '').slice(-1);
        const val = syncLivewire();
        if (this.value && idx < inputs.length - 1) inputs[idx + 1].focus();
        if (val.length === 6) setTimeout(() => submitBtn.click(), 300);
      });

      input.addEventListener('paste', function (e) {
        e.preventDefault();
        const pasted = (e.clipboardData || window.clipboardData).getData('text').replace(/[^0-9]/g, '').slice(0, 6);
        pasted.split('').forEach((char, i) => { if (inputs[i]) inputs[i].value = char; });
        syncLivewire();
        const nextEmpty = inputs.findIndex(inp => !inp.value);
        if (nextEmpty !== -1) inputs[nextEmpty].focus(); else inputs[5].focus();
      });
    });
  });
</script>
